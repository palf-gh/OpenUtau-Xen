"""Finds upstream strings that a language has not translated and writes Xen overlays for them.

Upstream OpenUtau dictionaries (OpenUtau/Strings/Strings.<culture>.axaml) are managed through Crowdin and are not
edited here. A key counts as untranslated when the language lacks it or keeps the English text. Translations are
kept in tools/xen-upstream-strings/<culture>.json ({key: text}) and written to
OpenUtau/Strings/XenUpstream.<culture>.axaml, which the application merges after the upstream dictionary.

  python tools/xen-upstream-strings.py missing   # writes tools/xen-upstream-strings/missing/<culture>.json
  python tools/xen-upstream-strings.py build     # writes the XenUpstream.<culture>.axaml overlays
"""
import glob
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STRINGS = os.path.join(ROOT, "OpenUtau", "Strings")
DATA = os.path.join(ROOT, "tools", "xen-upstream-strings")
X = "{http://schemas.microsoft.com/winfx/2006/xaml}Key"


def load(path):
    tree = ET.parse(path)
    return {element.get(X): element.text or "" for element in tree.getroot() if element.get(X)}


def cultures():
    for path in sorted(glob.glob(os.path.join(STRINGS, "Strings.*.axaml"))):
        yield os.path.basename(path)[len("Strings."):-len(".axaml")]


# Settings rather than text: font lists stay as each upstream dictionary sets them.
NOT_TEXT = {"ui.fontfamily"}


def untranslated(english, translated):
    return {key: text for key, text in english.items()
            if key not in NOT_TEXT and re.search(r"[a-z]{3}", text) and translated.get(key, text) == text}


def missing():
    english = load(os.path.join(STRINGS, "Strings.axaml"))
    os.makedirs(os.path.join(DATA, "missing"), exist_ok=True)
    for culture in cultures():
        done = {}
        path = os.path.join(DATA, culture + ".json")
        if os.path.exists(path):
            with open(path, encoding="utf-8") as file:
                done = json.load(file)
        todo = {key: text for key, text in untranslated(english, load(os.path.join(STRINGS, f"Strings.{culture}.axaml"))).items()
                if key not in done}
        with open(os.path.join(DATA, "missing", culture + ".json"), "w", encoding="utf-8", newline="\n") as file:
            json.dump(todo, file, ensure_ascii=False, indent=1)
        print(culture, len(todo))


def escape(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build():
    english = load(os.path.join(STRINGS, "Strings.axaml"))
    for culture in cultures():
        path = os.path.join(DATA, culture + ".json")
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as file:
            translations = json.load(file)
        needed = untranslated(english, load(os.path.join(STRINGS, f"Strings.{culture}.axaml")))
        lines = [
            '<ResourceDictionary xmlns="https://github.com/avaloniaui"',
            '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
            '                    xmlns:system="clr-namespace:System;assembly=System.Runtime">',
            f'  <!-- Generated by tools/xen-upstream-strings.py: upstream keys not yet translated in Strings.{culture}.axaml. -->',
        ]
        for key in english:
            if key in needed and key in translations:
                lines.append(f'  <system:String x:Key="{key}">{escape(translations[key])}</system:String>')
        lines.append("</ResourceDictionary>")
        with open(os.path.join(STRINGS, f"XenUpstream.{culture}.axaml"), "w", encoding="utf-8", newline="\n") as file:
            file.write("\n".join(lines) + "\n")
        print(culture, len(lines) - 5)


if __name__ == "__main__":
    {"missing": missing, "build": build}[sys.argv[1]]()
