using System;
using System.Collections.Generic;
using System.Globalization;
using Avalonia;
using Avalonia.Controls;
using Avalonia.Markup.Xaml.Styling;
using Avalonia.Styling;

namespace OpenUtau.App {
    /// <summary>Xen-owned overlays keep upstream Crowdin dictionaries untouched.</summary>
    public static class XenStrings {
        public static CultureInfo InputCulture { get; private set; } = CultureInfo.GetCultureInfo("en-US");
        public static string PresetName(Core.Microtonal.TuningDefinition tuning) => tuning.Id switch {
            "ji-5-limit" => Get("preset.ji5"),
            "ji-7-limit" => Get("preset.ji7"),
            "pythagorean" => Get("preset.pythagorean"),
            "meantone-quarter-comma" => Get("preset.quarter"),
            "meantone-sixth-comma" => Get("preset.sixth"),
            "rast-24edo-approximation" => Get("preset.rast"),
            "meantone-third-comma" => Get("preset.third"),
            "meantone-two-sevenths-comma" => Get("preset.twoSevenths"),
            "ptolemy-intense-diatonic" => Get("preset.ptolemy"),
            "harmonic-series-8-16" => Get("preset.harmonic"),
            "bohlen-pierce-just" => Get("preset.bpJust"),
            "shruti-22" => Get("preset.shruti"),
            "partch-43" => Get("preset.partch"),
            Core.Microtonal.TuningPresets.AeuId => Get("preset.aeu"),
            "slendro-5edo" => Get("preset.slendro"),
            Core.Microtonal.TuningPresets.PelogId => Get("preset.pelog"),
            "carlos-alpha" => Get("preset.alpha"),
            "carlos-beta" => Get("preset.beta"),
            "carlos-gamma" => Get("preset.gamma"),
            "equal-88-cent" => Get("preset.eightyEight"),
            "bohlen-pierce-13edt" => Get("preset.bp13"),
            "werckmeister-iii" => Get("preset.werckmeister"),
            "kirnberger-iii" => Get("preset.kirnberger"),
            "vallotti" => Get("preset.vallotti"),
            "young-ii" => Get("preset.young"),
            _ => GeneratedName(tuning) ?? tuning.Name,
        };

        /// <summary>
        /// Localises the generated equal-division names ("12-EDO", "13-ED (3/2)"); a name the user typed is kept.
        /// </summary>
        static string? GeneratedName(Core.Microtonal.TuningDefinition tuning) {
            if (tuning.Divisions <= 0) return null;
            string count = tuning.Divisions.ToString(CultureInfo.InvariantCulture);
            if (tuning.Name == count + "-EDO") return Get("preset.edo", count);
            string prefix = count + "-ED (";
            if (tuning.Name.StartsWith(prefix, StringComparison.Ordinal) && tuning.Name.EndsWith(')')) {
                return Get("preset.edx", count, tuning.Name[prefix.Length..^1]);
            }
            return null;
        }
        /// <summary>Avalonia asset root of this assembly; follows the executable name.</summary>
        public static readonly string AssetRoot = $"avares://{typeof(XenStrings).Assembly.GetName().Name}/";
        static readonly Dictionary<string, IResourceDictionary> dictionaries = new();
        public static IResourceDictionary GetResources(string language) {
            if (!dictionaries.TryGetValue(language, out var resource)) {
                resource = new ResourceInclude(new Uri(AssetRoot)) {
                    Source = new Uri($"{AssetRoot}Strings/Xen.{language}.axaml"),
                }.Loaded;
                dictionaries.Add(language, resource);
            }
            return resource;
        }
        static readonly Dictionary<string, IResourceDictionary?> upstreamOverlays = new();

        /// <summary>
        /// Translations of upstream keys that the Crowdin-managed dictionary of a language has not translated yet
        /// (generated by tools/xen-upstream-strings.py); null when the language has none.
        /// </summary>
        public static IResourceDictionary? GetUpstreamOverlay(string language) {
            if (language == "en-US") return null;
            if (!upstreamOverlays.TryGetValue(language, out var resource)) {
                try {
                    resource = new ResourceInclude(new Uri(AssetRoot)) {
                        Source = new Uri($"{AssetRoot}Strings/XenUpstream.{language}.axaml"),
                    }.Loaded;
                } catch (Exception) {
                    resource = null;
                }
                upstreamOverlays.Add(language, resource);
            }
            return resource;
        }

        public static void SetLanguage(string language) {
            InputCulture = CultureInfo.GetCultureInfo(language);
            if (Application.Current == null) return;
            foreach (var resource in dictionaries.Values) Application.Current.Resources.MergedDictionaries.Remove(resource);
            foreach (var resource in upstreamOverlays.Values) {
                if (resource != null) Application.Current.Resources.MergedDictionaries.Remove(resource);
            }
            Application.Current.Resources.MergedDictionaries.Add(GetResources("en-US"));
            if (language != "en-US") Application.Current.Resources.MergedDictionaries.Add(GetResources(language));
            // Merged after the upstream dictionary, so it fills only the keys upstream has left in English.
            if (GetUpstreamOverlay(language) is IResourceDictionary overlay) Application.Current.Resources.MergedDictionaries.Add(overlay);
        }
        public static string Get(string key, params object[] arguments) {
            string fullKey = key.StartsWith("xen.", StringComparison.Ordinal) ? key : "xen." + key;
            if (!ThemeManager.TryGetString(fullKey, out var text)) {
                text = GetResources("en-US").TryGetResource(fullKey, ThemeVariant.Default, out var fallback)
                    ? (string)fallback! : fullKey;
            }
            return arguments.Length == 0 ? text : string.Format(InputCulture, text, arguments);
        }
    }
}
